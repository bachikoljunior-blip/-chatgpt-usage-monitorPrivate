#!/usr/bin/env node

// The one thing that is not ours to change, and the only machine here that guards it.
//
// On 2026-08-10 the owner narrowed the permanent set from nine items to one:
//
//   最短で月収20万のみ変えないようにして、他の仕組みはそのままで、
//   子セッションが変えられるようにして
//
// That makes this repository's situation the inverse of what it was. Almost every
// guard here refuses something. This one refuses nothing — it only asserts that the
// goal still says what the owner said, because after the narrowing the goal is the
// entire fixed point, and a loop whose objective can be edited by the thing being
// optimised has no objective at all.
//
// Why it lives HERE rather than only in bachikoljunior-blip/note. note carries the
// canonical text, the mirror, the base64 backup, the manifest and
// scripts/check_directive_integrity.py, which is the real integrity system and is
// more thorough than this. It also runs in a repository this loop's hourly pulse
// cannot reach: pulse.yml holds a token scoped to this repository only. So the check
// that matters most was the one check guaranteed not to run on the schedule that
// never stops. This is the local half — cheap, self-contained, hourly.
//
//   node scripts/check-goal-intact.mjs
//
// What it checks, all against CLAUDE.md's generated PERMANENT-DIRECTIVE block:
//
//   1. the block exists at all — deletion is the loudest possible edit and would
//      otherwise be the quietest, since a missing block silences every rule in it
//   2. the fenced text hashes to the sha256 the block declares in its own header,
//      so an edit inside the fence cannot leave a header that vouches for it
//   3. the goal sentence is present verbatim
//
// 2 is the load-bearing one and it is deliberately self-referential: the block is
// generated by note/scripts/propagate_directive.py, which writes the hash from the
// manifest, so agreement between header and body means this copy is a faithful
// reproduction of whatever note published. It cannot detect note itself being
// rewritten — check_directive_integrity.py is for that — and saying so is the point,
// because a guard whose limits are unstated gets trusted past them.

import { readFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { resolve } from "node:path";
import { REPO } from "./state-source.mjs";

export const CLAUDE_MD = "CLAUDE.md";
export const BEGIN = "<!-- PERMANENT-DIRECTIVE:BEGIN -->";
export const END = "<!-- PERMANENT-DIRECTIVE:END -->";

// The goal, as the owner wrote it. Quoted rather than paraphrased, and short enough
// to be the sentence rather than the paragraph: a longer excerpt would go red on
// reformatting, which trains a reader to ignore it.
export const GOAL = "目標は最短で月収20万を達成することです";

/**
 * @param {string} text the whole CLAUDE.md
 * @returns {{ok: boolean, problems: string[], declared_sha: string|null, actual_sha: string|null}}
 */
export function checkGoal(text) {
  const problems = [];
  const begin = text.indexOf(BEGIN);
  const end = text.indexOf(END);
  if (begin < 0 || end < 0 || end < begin) {
    return {
      ok: false,
      problems: [
        "CLAUDE.md carries no PERMANENT-DIRECTIVE block. Deleting it removes every rule " +
          "in it at once and leaves nothing that looks wrong. Restore it with " +
          "note/scripts/propagate_directive.py --roots /home/user.",
      ],
      declared_sha: null,
      actual_sha: null,
    };
  }
  const block = text.slice(begin, end);

  const declared = block.match(/sha256=([0-9a-f]{64})/)?.[1] ?? null;
  if (!declared) problems.push("the block header declares no sha256, so nothing vouches for its body");

  // The fenced verbatim text, which is what the hash is over. The generator writes
  // the canonical file's bytes with the trailing newline restored by the fence.
  const fenceStart = block.indexOf("\n```\n");
  const fenceEnd = fenceStart < 0 ? -1 : block.indexOf("\n```\n", fenceStart + 4);
  let actual = null;
  if (fenceStart < 0 || fenceEnd < 0) {
    problems.push("the block has no fenced directive text, so there is nothing to hash");
  } else {
    const body = `${block.slice(fenceStart + 5, fenceEnd)}\n`;
    actual = createHash("sha256").update(body, "utf8").digest("hex");
    if (declared && actual !== declared) {
      problems.push(
        `the directive text does not match the sha256 its own header declares ` +
          `(header ${declared.slice(0, 16)}…, body ${actual.slice(0, 16)}…). Either the text was ` +
          "edited in place, or the block was copied from a different version. The owner's words " +
          "are not something a lap reconstructs — re-run note/scripts/propagate_directive.py.",
      );
    }
    if (!body.includes(GOAL)) {
      problems.push(
        `the goal sentence is missing from the directive text: ${JSON.stringify(GOAL)}. ` +
          "Since 2026-08-10 this is the whole of what is permanent; everything else in the " +
          "block is standing practice a child session may change.",
      );
    }
  }

  return { ok: problems.length === 0, problems, declared_sha: declared, actual_sha: actual };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = await readFile(resolve(REPO, CLAUDE_MD), "utf8");
  const verdict = checkGoal(text);
  console.log(
    `goal check: ${verdict.ok ? "intact" : "PROBLEM"}` +
      (verdict.actual_sha ? ` · directive sha ${verdict.actual_sha.slice(0, 16)}…` : ""),
  );
  for (const p of verdict.problems) console.log(`  ${p}`);
  if (!verdict.ok) process.exit(1);
}
